#!/usr/bin/env python3
"""
Renders the Quad app icon ("Golden Hour" gradient, "Sun on the Quad" mark: four lawn panels split by crossing
paths, the sun in the top-right cell, all solid white, on the amber -> dusk pink -> deep berry sunset gradient) from ONE geometry definition and writes every
platform asset:

  Android  androidApp/src/main/res/drawable/ic_launcher_background.xml      (vector, linear gradient)
           androidApp/src/main/res/drawable/ic_launcher_foreground.xml      (vector, white mark)
           androidApp/src/main/res/drawable/ic_launcher_monochrome.xml      (vector, themed-icon layer, Android 13+)
           androidApp/src/main/res/mipmap-anydpi-v26/ic_launcher{,_round}.xml  (adaptive icon incl. <monochrome>)
           androidApp/src/main/res/mipmap-*/ic_launcher{,_round}.png        (legacy launchers, API 24/25)
  iOS      iosApp/iosApp/Assets.xcassets/AppIcon.appiconset/app-icon-1024.png (opaque 1024x1024) + Contents.json

Colours are the Golden Hour brand gradient (shared/.../ui/theme/Theme.kt): Amber #FFC35A, Dusk pink #FF6B81 at 55%,
deep berry #B02A78, running from the top-left corner to the bottom-right corner.
Needs Python 3 and Pillow (`pip install pillow`). Run from anywhere:  python3 scripts/generate_app_icon.py
"""
import json
import math
import shutil
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "androidApp/src/main/res"
APPICON = ROOT / "iosApp/iosApp/Assets.xcassets/AppIcon.appiconset"

GRADIENT = [(0.0, "#FFC35A"), (0.55, "#FF6B81"), (1.0, "#B02A78")]  # amber -> dusk pink -> deep berry
MARK = "#FFFFFF"

# ---------------------------------------------------------------------------------------------------- geometry
# The approved "Sun on the Quad" drawing on a 96-unit grid (visual bounds 18..78 on both axes, so it is centred):
#   M18 44 V30 a12 12 0 0 1 12 -12 H44 V44 Z      top-left lawn panel, outer corner rounded r=12
#   circle cx=65 cy=31 r=13                        the sun, in the top-right cell
#   M18 52 H44 V78 H30 a12 12 0 0 1 -12 -12 Z     bottom-left panel
#   M52 52 H78 V66 a12 12 0 0 1 -12 12 H52 Z      bottom-right panel
# Same numbers as Brand.kt (QuadMark) and the server-rendered pages. Keep them in sync.
R = 12.0
PANELS = [  # (x0, y0, x1, y1, rounded corner)
    (18, 18, 44, 44, "tl"),
    (18, 52, 44, 78, "bl"),
    (52, 52, 78, 78, "br"),
]
SUN = (65.0, 31.0, 13.0)  # cx, cy, r
KIT_MID = (48.0, 48.0)

CENTER = 54.0
SCALE = 0.88  # kit units -> dp; the mark is ~53dp wide and its farthest point stays inside the 33dp safe radius


def xf(p):
    """Kit units -> 108dp adaptive-icon grid (mark centred)."""
    return (CENTER + (p[0] - KIT_MID[0]) * SCALE, CENTER + (p[1] - KIT_MID[1]) * SCALE)


# Android keeps launcher masks inside a 66x66dp (radius 33) safe zone: fail loudly if the artwork ever leaves it.
_corner_centres = [(30, 30), (30, 66), (66, 66)]
_reach = max(
    max(math.dist(xf(c), (CENTER, CENTER)) + R * SCALE for c in _corner_centres),
    math.dist(xf(SUN[:2]), (CENTER, CENTER)) + SUN[2] * SCALE,
)
assert _reach <= 33, f"mark leaves the adaptive-icon safe zone ({_reach:.2f}dp > 33dp)"


def _f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def _pt(x, y):
    px, py = xf((x, y))
    return f"{_f(px)},{_f(py)}"


def mark_paths():
    """Path data (108dp grid) for the three panels and the sun, as absolute commands with arcs."""
    r = _f(R * SCALE)
    tl = f"M{_pt(18, 44)}L{_pt(18, 30)}A{r},{r} 0 0 1 {_pt(30, 18)}L{_pt(44, 18)}L{_pt(44, 44)}Z"
    bl = f"M{_pt(18, 52)}L{_pt(44, 52)}L{_pt(44, 78)}L{_pt(30, 78)}A{r},{r} 0 0 1 {_pt(18, 66)}Z"
    br = f"M{_pt(52, 52)}L{_pt(78, 52)}L{_pt(78, 66)}A{r},{r} 0 0 1 {_pt(66, 78)}L{_pt(52, 78)}Z"
    cx, cy = xf(SUN[:2])
    sr = SUN[2] * SCALE
    sun = f"M{_f(cx - sr)},{_f(cy)}a{_f(sr)},{_f(sr)} 0 1,0 {_f(2 * sr)},0a{_f(sr)},{_f(sr)} 0 1,0 {_f(-2 * sr)},0Z"
    return [tl, sun, bl, br]


# ---------------------------------------------------------------------------------------------------- Android XML
def vector_head(extra_ns=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Generated by scripts/generate_app_icon.py. Do not edit by hand. -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n')


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def argb(hex_rgb: str) -> str:
    return "#FF" + hex_rgb.lstrip("#").upper()


def q_paths(color: str) -> str:
    return "".join(f'    <path\n        android:fillColor="{color}"\n        android:pathData="{d}" />\n'
                   for d in mark_paths())


def android_xml():
    # The gradient spans the part of the 108dp layer that launchers actually show (the inner 72dp), corner to corner,
    # so the amber and berry ends stay visible under every mask. Outside it the colours clamp.
    stops = "".join(f'                <item android:offset="{_f(o)}" android:color="{argb(c)}" />\n' for o, c in GRADIENT)
    write(RES / "drawable/ic_launcher_background.xml",
          vector_head('\n    xmlns:aapt="http://schemas.android.com/aapt"') +
          '    <path android:pathData="M0,0h108v108h-108z">\n'
          '        <aapt:attr name="android:fillColor">\n'
          '            <gradient\n'
          '                android:type="linear"\n'
          '                android:startX="18"\n                android:startY="18"\n'
          '                android:endX="90"\n                android:endY="90">\n'
          f'{stops}'
          '            </gradient>\n'
          '        </aapt:attr>\n'
          '    </path>\n</vector>\n')

    write(RES / "drawable/ic_launcher_foreground.xml", vector_head() + q_paths(argb(MARK)) + "</vector>\n")
    write(RES / "drawable/ic_launcher_monochrome.xml", vector_head() + q_paths("#FF000000") + "</vector>\n")

    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '    <background android:drawable="@drawable/ic_launcher_background" />\n'
                '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
                '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
                '</adaptive-icon>\n')
    for name in ("ic_launcher", "ic_launcher_round"):
        write(RES / f"mipmap-anydpi-v26/{name}.xml", adaptive)
    # The old template kept the foreground in drawable-v24/; it now lives in drawable/ (minSdk 24 supports vectors).
    old = RES / "drawable-v24"
    if old.exists():
        shutil.rmtree(old)


# ---------------------------------------------------------------------------------------------------- raster
SS = 4  # supersampling factor


def _rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _gradient_at(t):
    stops = [(o, _rgb(c)) for o, c in GRADIENT]
    t = min(max(t, 0.0), 1.0)
    for (o0, c0), (o1, c1) in zip(stops, stops[1:]):
        if t <= o1:
            k = (t - o0) / (o1 - o0)
            return tuple(round(a + (b - a) * k) for a, b in zip(c0, c1))
    return stops[-1][1]


def gradient_square(px: int) -> Image.Image:
    """Corner-to-corner diagonal gradient (SVG x1=0 y1=0 x2=1 y2=1): t = (x + y) / (2 * size)."""
    lut = bytearray()
    for i in range(2 * px):
        lut += bytes(_gradient_at((i + 1) / (2 * px)))
    rows = bytearray()
    for y in range(px):
        rows += lut[3 * y: 3 * (y + px)]
    return Image.frombytes("RGB", (px, px), bytes(rows))


def render(size: int, zoom: float, shape: str) -> Image.Image:
    """shape: 'full' (opaque square, iOS), 'rounded' / 'circle' (legacy Android launcher masks, transparent corners).
    [zoom] enlarges the mark about the centre, since these icons show the whole 108dp grid instead of its inner 72dp."""
    big = size * SS
    k = big / 108.0

    def sc(p):  # icon space -> pixels, zooming the mark about the centre
        return ((CENTER + (p[0] - CENTER) * zoom) * k, (CENTER + (p[1] - CENTER) * zoom) * k)

    img = gradient_square(big).convert("RGBA")

    mark = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(mark)
    corner = {"tl": (True, False, False, False), "bl": (False, False, False, True), "br": (False, False, True, False)}
    for x0, y0, x1, y1, c in PANELS:
        (ax, ay), (bx, by) = sc(xf((x0, y0))), sc(xf((x1, y1)))
        d.rounded_rectangle([ax, ay, bx - 1, by - 1], radius=R * SCALE * zoom * k, fill=255, corners=corner[c])
    sx, sy = sc(xf(SUN[:2]))
    sr = SUN[2] * SCALE * zoom * k
    d.ellipse([sx - sr, sy - sr, sx + sr, sy + sr], fill=255)
    img.paste(Image.new("RGBA", (big, big), _rgb(MARK) + (255,)), (0, 0), mark)

    if shape != "full":
        alpha = Image.new("L", (big, big), 0)
        ad = ImageDraw.Draw(alpha)
        if shape == "circle":
            ad.ellipse([0, 0, big - 1, big - 1], fill=255)
        else:
            ad.rounded_rectangle([0, 0, big - 1, big - 1], radius=int(big * 0.2), fill=255)
        img.putalpha(alpha)
    out = img.resize((size, size), Image.LANCZOS)
    if shape == "full":
        out = out.convert("RGB")  # App Store icons must not have an alpha channel
    return out


# Legacy and iOS icons show the full square, so the mark is enlarged to the kit's proportions (~61% of the width).
RASTER_ZOOM = 1.23


def raster_assets():
    for dens, px in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        d = RES / f"mipmap-{dens}"
        d.mkdir(parents=True, exist_ok=True)
        render(px, RASTER_ZOOM, "rounded").save(d / "ic_launcher.png", optimize=True)
        render(px, RASTER_ZOOM, "circle").save(d / "ic_launcher_round.png", optimize=True)

    APPICON.mkdir(parents=True, exist_ok=True)
    render(1024, RASTER_ZOOM, "full").save(APPICON / "app-icon-1024.png", optimize=True)
    contents = {
        "images": [{"filename": "app-icon-1024.png", "idiom": "universal", "platform": "ios", "size": "1024x1024"}],
        "info": {"author": "xcode", "version": 1},
    }
    write(APPICON / "Contents.json", json.dumps(contents, indent=2) + "\n")


if __name__ == "__main__":
    android_xml()
    raster_assets()
    print("Wrote Android vector/adaptive/legacy icons and the iOS AppIcon set.")
